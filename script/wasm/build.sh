#!/bin/sh
# Builds the cloth solver's WebAssembly (script/wasm/cloth.c) into lib/garments/cloth_wasm.js, the module's
# bytes as base64, so the page, its drape worker and Node load it the same way, with no fetch. Needs clang
# (with the wasm32 target) and wasm-ld; any clang 15 or later. -O2, not -O3: unrolled, the module passes 4 KB,
# the most a page may compile at once on its main thread.
#
#   sh script/wasm/build.sh
set -e
cd "$(dirname "$0")/../.."
out=$(mktemp -d)
clang --target=wasm32 -O2 -nostdlib -fno-builtin -Wl,--no-entry -Wl,--export-memory -Wl,--strip-all \
  -o "$out/cloth.wasm" script/wasm/cloth.c
bytes=$(wc -c < "$out/cloth.wasm" | tr -d ' ')
{
  echo "// Generated by script/wasm/build.sh from script/wasm/cloth.c ($bytes bytes): the cloth solver's inner loops."
  echo "// Don't edit; change cloth.c and build again."
  printf 'export const CLOTH_WASM = "'
  base64 -w0 "$out/cloth.wasm" 2>/dev/null || base64 "$out/cloth.wasm" | tr -d '\n'
  echo '"'
} > app/javascript/lib/garments/cloth_wasm.js
rm -rf "$out"
echo "wrote app/javascript/lib/garments/cloth_wasm.js ($bytes bytes of WebAssembly)"
